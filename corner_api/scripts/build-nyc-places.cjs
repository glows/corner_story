const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const places = JSON.parse(fs.readFileSync(path.join(root, 'data/nyc_places.json'), 'utf8'));
const quote = value => value == null ? 'NULL' : typeof value === 'number' ? String(value) : `'${String(value).replaceAll("'", "''")}'`;
const columns = ['id', 'name', 'city', 'neighborhood', 'address', 'price_tier', 'category', 'badge', 'rating', 'description', 'acoustic_note', 'hours_text', 'walk_info', 'cover_url', 'marker_url', 'social_proof_text', 'lat', 'lng', 'has_live_vibe'];
const statements = [
  '-- Generated by scripts/build-nyc-places.cjs from data/nyc_places.json.',
  '-- Additive/idempotent: preserves existing bookmarks, notes and other cities.',
  `CREATE TABLE IF NOT EXISTS spot_sources (
    spot_id TEXT PRIMARY KEY,
    website_url TEXT NOT NULL,
    sources_json TEXT NOT NULL,
    verified_at TEXT NOT NULL,
    coordinate_source TEXT NOT NULL,
    notes TEXT NOT NULL DEFAULT ''
  );`,
];
for (const place of places) {
  const row = {...place, price_tier: place.price_tier ?? '', walk_info: place.address};
  statements.push(`INSERT INTO spots (${columns.join(', ')}) VALUES (${columns.map(key => quote(row[key])).join(', ')})\nON CONFLICT(id) DO UPDATE SET ${columns.filter(key => key !== 'id').map(key => `${key}=excluded.${key}`).join(', ')};`);
  statements.push(`INSERT INTO spot_sources (spot_id, website_url, sources_json, verified_at, coordinate_source, notes) VALUES (${[place.id, place.website_url, JSON.stringify(place.sources), place.verified_at, place.coordinate_source, place.notes].map(quote).join(', ')})\nON CONFLICT(spot_id) DO UPDATE SET website_url=excluded.website_url, sources_json=excluded.sources_json, verified_at=excluded.verified_at, coordinate_source=excluded.coordinate_source, notes=excluded.notes;`);
}
const asset = path.resolve(root, '../corner_story/assets/data/nyc_places.json');
fs.mkdirSync(path.dirname(asset), {recursive: true});
fs.writeFileSync(asset, JSON.stringify(places, null, 2) + '\n');
const photoEntries = places.filter(place => place.image_r2_key);
fs.writeFileSync(path.resolve(root, '../corner_story/lib/services/place_photos.dart'),
  '// Generated by build-nyc-places.cjs. Keep photo sources in nyc_places.json.\n' +
  'const placePhotoUrls = <String, String>{\n' + photoEntries.flatMap(place =>
    [place.image_original_url, place.image_legacy_asset,
      place.cover_url.replace('https://corner-api.flymind.org/', 'https://corner-api.ne0web64.workers.dev/')].map(source =>
      `  ${JSON.stringify(source)}: ${JSON.stringify(place.cover_url)},`)).join('\n') + '\n};\n\n' +
  'const placePhotoCredits = <String, String>{\n' + photoEntries.map(place =>
    `  ${JSON.stringify(place.cover_url)}: ${JSON.stringify(place.image_credit + '\n' + place.image_source_url)},`).join('\n') + '\n};\n');
fs.writeFileSync(path.join(root, 'migrations/0006_nyc_place_photos.sql'),
  '-- Photo-only update: preserves venue details and all user data.\n' + photoEntries.map(place =>
    `UPDATE spots SET cover_url=${quote(place.image_original_url)}, marker_url=${quote(place.image_original_url)} WHERE id=${quote(place.id)};`).join('\n') + '\n');
fs.writeFileSync(path.join(root, 'migrations/0009_photo_custom_domain.sql'),
  '-- Use the reachable custom domain for R2 photos; preserve all user data.\n' + photoEntries.map(place =>
    `UPDATE spots SET cover_url=${quote(place.cover_url)}, marker_url=${quote(place.marker_url)} WHERE id=${quote(place.id)};`).join('\n') + '\n');
fs.writeFileSync(path.join(root, 'migrations/0005_verified_nyc_places.sql'), statements.join('\n\n') + '\n');
console.log(`Generated SQL and Flutter asset for ${places.length} verified NYC places.`);
